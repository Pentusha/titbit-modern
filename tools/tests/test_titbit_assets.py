class AssetImportTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.source = self.root / 'source'
        self.source.mkdir()
        self.target = self.root / 'target'
        self.target.mkdir()
        self.payloads = {'QUEST.ezd': b'test archive' * 13}
        self.payloads.update({f'clip{i:02}.avi': bytes([i]) * (20 + i) for i in range(18)})
        self.records = {name: {'size': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
                        for name, data in self.payloads.items()}
        for name, data in self.payloads.items():
            (self.source/name).write_bytes(data)
        self.manifest = self.root / 'assets.json'
        self.write_manifest({'version': 1, 'files': self.records})
        self.patch = mock.patch.object(assets, 'MANIFEST', self.manifest)
        self.patch.start()
        self.addCleanup(self.patch.stop)
        self.addCleanup(self.temp.cleanup)

    def write_manifest(self, data):
        self.manifest.write_text(json.dumps(data), encoding='utf-8')

    def inspect(self):
        plan = assets.inspect_source(self.source)
        self.addCleanup(plan.close)
        return plan

    def assert_only_saves_remain(self):
        self.assertEqual(sorted(p.name for p in self.target.iterdir()), ['savegame.dat'])
        self.assertEqual((self.target/'savegame.dat').read_bytes(), b'keep my save')

    def save(self):
        (self.target/'savegame.dat').write_bytes(b'keep my save')

    def test_install_verify_reuse_preserves_saves_and_originals(self):
        self.save()
        plan = self.inspect()
        progress = []
        result = assets.install_assets(plan, self.target, progress=lambda *p: progress.append(p))
        self.assertEqual(result['installed'], 19)
        self.assertEqual(result['reused'], 0)
        self.assertEqual(assets.verify_install(self.target)['verified'], 19)
        self.assertEqual(progress[-1][1], sum(len(p) for p in self.payloads.values()))
        self.assertTrue(all(a[1] <= b[1] for a, b in zip(progress, progress[1:])))
        again = assets.install_assets(plan, self.target)
        self.assertEqual((again['installed'], again['reused']), (0, 19))
        self.assertEqual((self.target/'savegame.dat').read_bytes(), b'keep my save')
        for name, data in self.payloads.items():
            self.assertEqual((self.source/name).read_bytes(), data)

    def test_cancel_after_staging_started_commits_no_assets(self):
        self.save()
        cancel = threading.Event()
        def progress(name, done, total):
            if name in self.payloads:
                cancel.set()
        with self.assertRaises(assets.ImportCancelled):
            assets.install_assets(self.inspect(), self.target, progress=progress, cancel=cancel)
        self.assert_only_saves_remain()

    def test_source_changes_after_preview_no_partial_commit(self):
        self.save()
        plan = self.inspect()
        name = list(self.payloads)[-1]
        data = self.payloads[name]
        (self.source/name).write_bytes(bytes([data[0] ^ 1]) + data[1:])
        with self.assertRaisesRegex(ValueError, 'SHA256'):
            assets.install_assets(plan, self.target)
        self.assert_only_saves_remain()

    def test_refuse_modified_target_without_changing_anything(self):
        self.save()
        name = 'QUEST.ezd'
        modified = b'x' * len(self.payloads[name])
        (self.target/name).write_bytes(modified)
        with self.assertRaisesRegex(ValueError, 'не перезаписываются'):
            assets.install_assets(self.inspect(), self.target)
        self.assertEqual((self.target/name).read_bytes(), modified)
        self.assertEqual(len(list(self.target.iterdir())), 2)
        self.assertEqual((self.target/'savegame.dat').read_bytes(), b'keep my save')

    def test_existing_valid_file_reused_when_other_assets_fail(self):
        self.save()
        (self.target/'QUEST.ezd').write_bytes(self.payloads['QUEST.ezd'])
        plan = self.inspect()
        (self.source/'clip17.avi').write_bytes(b'x' * len(self.payloads['clip17.avi']))
        with self.assertRaises(ValueError):
            assets.install_assets(plan, self.target)
        self.assertEqual((self.target/'QUEST.ezd').read_bytes(), self.payloads['QUEST.ezd'])
        self.assertEqual(sorted(p.name for p in self.target.iterdir()), ['QUEST.ezd', 'savegame.dat'])

    def test_concurrent_destination_file_survives_failed_commit(self):
        self.save()
        foreign = self.target/'clip17.avi'
        def progress(name, done, total):
            if done == total:
                foreign.write_bytes(b'created by another process')
        with self.assertRaises((OSError, ValueError)):
            assets.install_assets(self.inspect(), self.target, progress=progress)
        self.assertEqual(foreign.read_bytes(), b'created by another process')
        self.assertEqual(sorted(p.name for p in self.target.iterdir()), ['clip17.avi', 'savegame.dat'])

    def test_low_disk_space_preserves_existing_files(self):
        self.save()
        with mock.patch.object(assets.shutil, 'disk_usage', return_value=type('Disk', (), {'free': 0})()):
            with self.assertRaisesRegex(ValueError, 'Недостаточно свободного места'):
                assets.install_assets(self.inspect(), self.target)
        self.assert_only_saves_remain()

    def test_verify_detects_same_size_modification(self):
        assets.install_assets(self.inspect(), self.target)
        name = 'clip07.avi'
        (self.target/name).write_bytes(b'x' * len(self.payloads[name]))
        with self.assertRaisesRegex(ValueError, 'повреждён или изменён'):
            assets.verify_install(self.target)

    def test_incomplete_source_rejected_before_copying(self):
        (self.source/'clip17.avi').unlink()
        with self.assertRaises(ValueError):
            assets.inspect_source(self.source)
        self.assertEqual(list(self.target.iterdir()), [])

    def test_ambiguous_two_complete_copies_rejected(self):
        nested = self.source/'another-copy'
        nested.mkdir()
        for name, data in self.payloads.items():
            (nested/name).write_bytes(data)
        with self.assertRaisesRegex(ValueError, 'несколько копий'):
            assets.inspect_source(self.source)

    def test_manifest_bad_schema_reports_value_error(self):
        variants = [[], {'version': 1, 'files': []}, {'version': 0, 'files': self.records}]
        for record in ({}, {'size': '10', 'sha256': '0'*64}, {'size': True, 'sha256': '0'*64},
                       {'size': 10, 'sha256': 'not a hash'}, {'size': -1, 'sha256': '0'*64}):
            records = dict(self.records)
            records['QUEST.ezd'] = record
            variants.append({'version': 1, 'files': records})
        for index, data in enumerate(variants):
            with self.subTest(variant=index):
                self.write_manifest(data)
                with self.assertRaises(ValueError):
                    assets.manifest()

    def test_manifest_cannot_escape_destination(self):
        records = dict(self.records)
        records['../escape.avi'] = records.pop('clip00.avi')
        self.write_manifest({'version': 1, 'files': records})
        with self.assertRaises(ValueError):
            assets.manifest()


class CabinetBoundaryTests(unittest.TestCase):
    def deflate(self, data):
        compressor = zlib.compressobj(wbits=-15)
        return compressor.compress(data) + compressor.flush()

    def cabinet(self, payload, flags, expanded, digest):
        data = struct.pack('<I', 0x28635349) + bytes(80) + payload
        source = type('MemorySource', (), {'open': lambda self, name: io.BytesIO(data)})()
        cab = assets.Cabinet.__new__(assets.Cabinet)
        cab.source = source
        cab.files = {'clip.avi': ('data2.cab', flags, expanded, len(payload), 84, digest)}
        return cab

    def test_uncompressed_bad_md5_rejected(self):
        cab = self.cabinet(b'payload', 0, 7, bytes(16))
        with self.assertRaisesRegex(ValueError, 'Контрольная сумма'):
            b''.join(cab.chunks('clip.avi'))

    def test_compressed_chunk_length_cannot_cross_cabinet_boundary(self):
        cab = self.cabinet(struct.pack('<H', 100) + b'x', 4, 10, bytes(16))
        with self.assertRaisesRegex(ValueError, 'размер блока'):
            b''.join(cab.chunks('clip.avi'))

    def test_compressed_block_larger_than_64k_rejected(self):
        raw = self.deflate(b'x' * 65537)
        cab = self.cabinet(struct.pack('<H', len(raw)) + raw, 4, 65537, hashlib.md5(b'x'*65537).digest())
        with self.assertRaisesRegex(ValueError, 'слишком большой блок'):
            b''.join(cab.chunks('clip.avi'))

    def test_valid_compressed_chunk_roundtrip(self):
        data = b'test data' * 100
        raw = self.deflate(data)
        cab = self.cabinet(struct.pack('<H', len(raw)) + raw, 4, len(data), hashlib.md5(data).digest())
        self.assertEqual(b''.join(cab.chunks('clip.avi')), data)


@unittest.skipUnless(os.environ.get('TITBIT_TEST_FILES'), 'Set TITBIT_TEST_FILES for original-data checks')
class OriginalCopyTests(unittest.TestCase):
    def test_cli_full_original_folder_verification(self):
        setup = Path(__file__).resolve().parents[1] / 'titbit_setup.py'
        result = subprocess.run([sys.executable, '-X', 'utf8', str(setup), '--verify', os.environ['TITBIT_TEST_FILES']],
                                capture_output=True, text=True, encoding='utf-8', timeout=180)
        self.assertEqual(result.returncode, 0, result.stderr)
        report = json.loads(result.stdout)
        self.assertEqual(report['verified'], 19)
        self.assertEqual(report['bytes'], 311181440)


